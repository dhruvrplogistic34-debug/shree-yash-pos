// Helper to generate past ISO timestamps
const now = new Date();
const getPastDate = (daysAgo: number, hour: number, minute: number = 0) => {
  const d = new Date(now);
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

